#include <unistd.h>

int	main(int ac, char **av)
{
	int	i = 0;
	int j = 0;
	int x = 0;
	
	if (ac == 3)
	{
		while (av[2][j])
		{
			if (av[1][i] && av[2][j] == av[1][i])
				i++;
			if (av[1][i] == '\0')
			{
				while (av[1][x])
				{
					write(1, &av[1][x], 1);
					x++;
				}
			}
			j++;
		}
	}
}