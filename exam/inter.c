int main(int ac, char **av)
{
    int i;
    char tab[256] = {0};

    i = 0;
    if (ac == 3)
    {
        while (av[1][i])
        {
            if(tab[av[1][i] - '0'] == 0)
            {
                tab[(int)av[1][i]] = 1;
                write(1, &av[1][i], 1);
            }
            i++;
        }
        i = 0;
        while (av[2][i])
        {
            if(tab[(int)av[2][i]] == 0)
            {
                tab[(int)av[2][i]] = 1;
                write(1, &av[2][i], 1);
            }
            i++;
        }
    }
}