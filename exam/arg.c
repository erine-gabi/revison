#include <unistd.h>

int     main(int argc, char **argv)
{
    int     j;
    
    j = argc - 1;
    while(argc != j)
    {
        int i = 0;
        while(argv[j][i])
        {
                    write(1, &argv[j][i], 1);
            i++;
}
        j++;
    }
}